@router.put("/pages/{page_id}")
async def update_page(page_id: str, body: PageUpdate, db: AsyncSession = Depends(get_db),
                      ctx: WorkspaceContext = Depends(require_permission("builder:write"))):
    p = ctx.ensure(await db.get(SitePage, uuid.UUID(page_id)), "Page")
    if body.name is not None:
        p.name = security_manager.sanitize_text(body.name, 160)
    if body.blocks is not None:
        p.blocks = _clean_blocks(body.blocks)
    if body.theme is not None:
        p.theme = {**DEFAULT_THEME, **{k: str(v)[:60] for k, v in body.theme.items()}}
    if p.published:  # keep the live site in sync with every save
        p.published_html = _html(p)
    await db.commit()
    return _page(p, full=True)


