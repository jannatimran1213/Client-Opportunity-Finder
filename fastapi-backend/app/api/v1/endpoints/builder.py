@router.post("/pages")
async def create_page(body: PageIn, db: AsyncSession = Depends(get_db), ctx: WorkspaceContext = Depends(require_permission("builder:write"))):
    count = (await db.execute(select(func.count()).select_from(SitePage).where(SitePage.workspace_id == ctx.workspace.id))).scalar()
    await enforce_limit(db, ctx.workspace.id, "pages", current=count)
    blocks, theme, kind, name = [], dict(DEFAULT_THEME), body.kind, body.name
    if body.template_key:
        try:
            t = instantiate(body.template_key)
        except KeyError:
            raise HTTPException(status_code=404, detail="Template not found")
        blocks, theme, kind = t["blocks"], {**DEFAULT_THEME, **t["theme"]}, t["kind"]
        name = body.name if body.name != "Untitled page" else t["name"]
    biz = None
    if body.business_id:
        biz = (await db.execute(select(SavedBusiness).where(SavedBusiness.id == uuid.UUID(body.business_id), lead_scope(ctx)))).scalars().first()
        if biz:  # personalise a template for a prospect (great for "here is a redesign" outreach)
            for b in blocks:
                pr = b["props"]
                if b["type"] == "hero":
                    pr["heading"] = f"{biz.business_name}"
                if b["type"] == "contact":
                    pr.update({k: v for k, v in {"email": biz.email, "phone": biz.phone, "address": biz.address}.items() if v})
                if b["type"] == "footer":
                    pr["text"] = f"Â© {biz.business_name}"
    p = SitePage(workspace_id=ctx.workspace.id, business_id=biz.id if biz else None, name=security_manager.sanitize_text(name, 160),
                 kind=kind, template_key=body.template_key, blocks=blocks, theme=theme)
    db.add(p)
    await db.commit()
    return _page(p, full=True)


