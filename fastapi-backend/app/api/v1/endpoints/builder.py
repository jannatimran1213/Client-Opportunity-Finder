async def serve_site(db: AsyncSession, sub: str) -> HTMLResponse:
    p = (await db.execute(select(SitePage).where(SitePage.subdomain == security_manager.sanitize_subdomain(sub),
                                                 SitePage.published == True))).scalars().first()  # noqa: E712
    if not p or not p.published_html:
        return HTMLResponse("<h1>Site not found</h1><p>This page is not published.</p>", status_code=404)
    p.view_count = (p.view_count or 0) + 1
    await db.commit()
    return HTMLResponse(p.published_html, headers={"X-Frame-Options": "SAMEORIGIN", "X-Content-Type-Options": "nosniff",
                                                   "Referrer-Policy": "strict-origin-when-cross-origin"})


@public_router.get("/{sub}", response_class=HTMLResponse)
async def public_site(sub: str, db: AsyncSession = Depends(get_db)):
    return await serve_site(db, sub)


@public_router.post("/{sub}/contact", response_class=HTMLResponse)
async def public_contact(sub: str, request: Request, db: AsyncSession = Depends(get_db)):
    """Contact-form block on hosted pages: each submission becomes a lead + notification in the owner's workspace."""
    ok, retry = security_manager.check_rate_limit(f"form:{request.client.host if request.client else ''}:{sub}", 5, 600)
    if not ok:
        return HTMLResponse("<p>Too many submissions, please try later.</p>", status_code=429)
    p = (await db.execute(select(SitePage).where(SitePage.subdomain == sub, SitePage.published == True))).scalars().first()  # noqa: E712
    if not p:
        return HTMLResponse("Not found", status_code=404)
    form = await request.form()
    name = security_manager.sanitize_text(form.get("name"), 120) or "Website visitor"
    email = security_manager.sanitize_text(form.get("email"), 200)
    msg = security_manager.sanitize_text(form.get("message"), 3000)
    ws = await db.get(Workspace, p.workspace_id)
    db.add(SavedBusiness(user_id=ws.owner_id, workspace_id=ws.id, business_name=name, email=email or None,
                         phone=security_manager.sanitize_text(form.get("phone"), 60) or None, category="Website enquiry",
                         notes=f"From page '{p.name}': {msg}"))
    db.add(Notification(workspace_id=ws.id, title=f"New enquiry from {p.subdomain}", body=f"{name} ({email}): {msg[:200]}", link="/leads"))
    await db.commit()
    return HTMLResponse("<html><body style='font-family:sans-serif;text-align:center;padding:60px'><h2>Thank you!</h2>"
                        "<p>We received your message and will reply soon.</p><a href='javascript:history.back()'>Back</a></body></html>")

