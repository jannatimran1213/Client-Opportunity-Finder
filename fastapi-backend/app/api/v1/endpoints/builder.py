@router.get("/pages/{page_id}/export")
async def export(page_id: str, db: AsyncSession = Depends(get_db), ctx: WorkspaceContext = Depends(require_permission("leads:read"))):
    p = ctx.ensure(await db.get(SitePage, uuid.UUID(page_id)), "Page")
    slug = security_manager.sanitize_subdomain(p.subdomain or p.name) or "page"
    buf = io.BytesIO()
    with zipfile.ZipFile(buf, "w", zipfile.ZIP_DEFLATED) as z:
        if p.kind == "email":
            z.writestr("email.html", _html(p))
        else:
            z.writestr("index.html", _html(p, inline_css=False))
            z.writestr("styles.css", css(p.theme or {}))
            z.writestr("script.js", EXPORT_JS)
            z.writestr("index.inline.html", _html(p))
        z.writestr("page.json", json.dumps({"name": p.name, "kind": p.kind, "theme": p.theme, "blocks": p.blocks}, indent=2))
        z.writestr("README.txt", f"{p.name}\n\nExported from AI Client Hunt Builder on {datetime.utcnow():%Y-%m-%d}.\n"
                                 "index.html + styles.css + script.js: upload to any static host (Netlify, Vercel, cPanel, S3).\n"
                                 "index.inline.html: single-file version with CSS inlined.\n"
                                 "page.json: the editable design; import it back into the builder.\n")
    buf.seek(0)
    return StreamingResponse(buf, media_type="application/zip", headers={"Content-Disposition": f'attachment; filename="{slug}.zip"'})


