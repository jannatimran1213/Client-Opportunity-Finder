@router.get("/pages")
async def list_pages(db: AsyncSession = Depends(get_db), ctx: WorkspaceContext = Depends(require_permission("leads:read"))):
    rows = (await db.execute(select(SitePage).where(SitePage.workspace_id == ctx.workspace.id).order_by(SitePage.updated_at.desc()))).scalars().all()
