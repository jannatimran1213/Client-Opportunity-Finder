@router.post("/pages/{page_id}/publish")
async def publish(page_id: str, body: PublishIn, db: AsyncSession = Depends(get_db),
                  ctx: WorkspaceContext = Depends(require_permission("builder:publish"))):
    p = ctx.ensure(await db.get(SitePage, uuid.UUID(page_id)), "Page")
    if p.kind == "email":
        raise HTTPException(status_code=400, detail="Email designs are exported or sent, not hosted")
    sub = security_manager.sanitize_subdomain(body.subdomain)
    if len(sub) < 3:
        raise HTTPException(status_code=400, detail="Subdomain must be at least 3 characters (a-z, 0-9, -)")
    other = (await db.execute(select(SitePage).where(SitePage.subdomain == sub, SitePage.id != p.id))).scalars().first()
    if other:
        raise HTTPException(status_code=409, detail="That subdomain is taken")
    p.subdomain, p.published, p.published_at = sub, True, datetime.now(timezone.utc)
    p.published_html = _html(p)
    await db.commit()
    return _page(p)


